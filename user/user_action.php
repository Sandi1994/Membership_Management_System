
<?php

if (session_status() === PHP_SESSION_NONE) {
    session_start();
}

if (!isset($_SESSION['user_id'])) {
    header('Location: ../auth/login.php');
    exit();
}

require_once __DIR__ . '/../config/config.php';

/* Escape output */
function h($value)
{
    return htmlspecialchars((string)$value, ENT_QUOTES, 'UTF-8');
}

/* Redirect to User Find page */
function redirect_user_list($showDeleted, $status = '', $error = '')
{
    $url = 'user_find.php';

    if ($showDeleted) {
        $url .= '?show_deleted=1';
    }

    if ($status !== '') {
        $url .= (strpos($url, '?') === false ? '?' : '&')
              . 'status=' . urlencode($status);
    }

    if ($error !== '') {
        $url .= (strpos($url, '?') === false ? '?' : '&')
              . 'error=' . urlencode($error);
    }

    header('Location: ' . $url);
    exit();
}

/* POST requests only */
if ($_SERVER['REQUEST_METHOD'] !== 'POST') {
    redirect_user_list(false, '', 'invalid_request');
}

/* Validate CSRF token */
if (
    !isset($_POST['csrf_token']) ||
    !isset($_SESSION['csrf_token'])
) {
    redirect_user_list(false, '', 'invalid_request');
}

$postedToken = (string)$_POST['csrf_token'];
$sessionToken = (string)$_SESSION['csrf_token'];

if (!hash_equals($sessionToken, $postedToken)) {
    redirect_user_list(false, '', 'invalid_request');
}

/* Request details */
$showDeleted = isset($_POST['show_deleted'])
    && $_POST['show_deleted'] === '1';

$userId = isset($_POST['user_id'])
    ? (int)$_POST['user_id'] : 0;

$action = isset($_POST['action'])
    ? (string)$_POST['action'] : '';

$currentUserId = (int)$_SESSION['user_id'];

$roleId = isset($_SESSION['role_id'])
    ? (int)$_SESSION['role_id'] : 0;

/* Role permissions */
$isManager = ($roleId === 3);
$isOps = ($roleId === 4);

if (!$isManager && !$isOps) {
    header('HTTP/1.1 403 Forbidden');
    exit('Access denied.');
}

/* Prevent invalid user IDs and self-account changes */
if ($userId < 1 || $userId === $currentUserId) {
    redirect_user_list($showDeleted, '', 'invalid_target');
}


/* =========================================
   DEACTIVATE ACCOUNT
   Manager and Membership Ops
========================================= */

if ($action === 'soft_delete') {

    $stmt = $conn->prepare(
        'UPDATE users
         SET is_deleted = 1,
             is_active = 0
         WHERE user_id = ?
         AND is_deleted = 0'
    );

    if (!$stmt) {
        redirect_user_list(false, '', 'action_failed');
    }

    $stmt->bind_param('i', $userId);

    $ok = $stmt->execute();
    $changed = $stmt->affected_rows;

    $stmt->close();

    if ($ok && $changed === 1) {
        redirect_user_list(false, 'soft_deleted', '');
    }

    redirect_user_list(false, '', 'action_failed');
}


/* =========================================
   REACTIVATE ACCOUNT
   Manager only
========================================= */

if ($action === 'restore') {

    if (!$isManager) {
        header('HTTP/1.1 403 Forbidden');
        exit('Manager permission required.');
    }

    $stmt = $conn->prepare(
        'UPDATE users
         SET is_deleted = 0,
             is_active = 1
         WHERE user_id = ?
         AND is_deleted = 1'
    );

    if (!$stmt) {
        redirect_user_list(true, '', 'action_failed');
    }

    $stmt->bind_param('i', $userId);

    $ok = $stmt->execute();
    $changed = $stmt->affected_rows;

    $stmt->close();

    if ($ok && $changed === 1) {
        redirect_user_list(true, 'restored', '');
    }

    redirect_user_list(true, '', 'action_failed');
}


/* =========================================
   PERMANENT DELETE
   Manager only
   Active and deactivated users allowed
========================================= */

if ($action === 'hard_delete') {

    // Permanent deletion is restricted to Membership Manager.
    if (!$isManager) {
        header('HTTP/1.1 403 Forbidden');
        exit('Manager permission required.');
    }

    // The Bootstrap modal must submit an explicit confirmation.
    if (!isset($_POST['confirm_delete']) ||
        $_POST['confirm_delete'] !== '1') {
        redirect_user_list($showDeleted, '', 'invalid_request');
    }

    // Validate the one-time confirmation token generated by user_find.php.
    $confirmationToken = isset($_POST['confirmation_token'])
        ? (string)$_POST['confirmation_token'] : '';

    $confirmations = isset($_SESSION['delete_confirmations']) &&
                     is_array($_SESSION['delete_confirmations'])
        ? $_SESSION['delete_confirmations'] : array();

    $confirmation = isset($confirmations[$userId])
        ? $confirmations[$userId] : null;

    if (
        !$confirmation ||
        !isset($confirmation['token'], $confirmation['created']) ||
        (time() - (int)$confirmation['created']) > 300 ||
        !hash_equals((string)$confirmation['token'], $confirmationToken)
    ) {
        redirect_user_list($showDeleted, '', 'invalid_request');
    }

    // Consume the token before attempting deletion so it cannot be replayed.
    unset($_SESSION['delete_confirmations'][$userId]);

    // Confirm that the target still exists. Active and deactivated users are allowed.
    $checkStmt = $conn->prepare(
        'SELECT user_id
         FROM users
         WHERE user_id = ?
         LIMIT 1'
    );

    if (!$checkStmt) {
        redirect_user_list($showDeleted, '', 'action_failed');
    }

    $checkStmt->bind_param('i', $userId);

    if (!$checkStmt->execute()) {
        $checkStmt->close();
        redirect_user_list($showDeleted, '', 'action_failed');
    }

    $result = $checkStmt->get_result();
    $user = $result ? $result->fetch_assoc() : null;
    $checkStmt->close();

    if (!$user) {
        redirect_user_list($showDeleted, '', 'invalid_target');
    }

    // Delete only after Manager, CSRF, target, and one-time modal token checks pass.
    $stmt = $conn->prepare(
        'DELETE FROM users
         WHERE user_id = ?'
    );

    if (!$stmt) {
        redirect_user_list($showDeleted, '', 'related_records');
    }

    $stmt->bind_param('i', $userId);
    $ok = $stmt->execute();
    $changed = $stmt->affected_rows;
    $stmt->close();

    if ($ok && $changed === 1) {
        redirect_user_list($showDeleted, 'hard_deleted', '');
    }

    // Foreign-key constraints may prevent deletion when related records exist.
    redirect_user_list($showDeleted, '', 'related_records');
}

/* Invalid action */

redirect_user_list($showDeleted, '', 'invalid_action');

?>
